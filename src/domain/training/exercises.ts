const BY_ID = new Map(EXERCISES.map((exercise) => [exercise.id, exercise]));

if (BY_ID.size !== EXERCISES.length) {
  throw new Error('Exercise catalog has duplicate ids');
}

export function getExercise(id: string): Exercise {
  const exercise = BY_ID.get(id);
  if (!exercise) throw new Error(`Unknown exercise: ${id}`);
  return exercise;
}

export function findExercise(id: string): Exercise | undefined {
  return BY_ID.get(id);
}

/** Exercises for a pattern that this equipment allows, most preferred first. */
export function exercisesFor(pattern: Pattern, equipment: Equipment): Exercise[] {
  return EXERCISES.filter((exercise) => exercise.pattern === pattern && exercise.equipment.includes(equipment));
}
